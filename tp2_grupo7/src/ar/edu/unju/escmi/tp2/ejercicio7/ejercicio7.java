package ar.edu.unju.escmi.tp2.ejercicio7;

public class ejercicio7 {
    public static void main(String[] args) {
        int a = 30;
        double b = 1.5;

        System.out.println("a++ (sufijo): " + a++); 
        System.out.println("a después de a++: " + a); 
        System.out.println("--a (prefijo): " + --a); 

        System.out.println("++b (prefijo): " + ++b); 
        System.out.println("b-- (sufijo): " + b--); 
        System.out.println("b después de b--: " + b);
    }
}
