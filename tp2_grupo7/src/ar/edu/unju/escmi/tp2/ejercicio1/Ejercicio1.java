package ar.edu.unju.escmi.tp2.ejercicio1;

public class Ejercicio1 {

    public static void main(String[] args) {
        // Número de DNI
        int dni = 47438119;
        System.out.println("Mi número de DNI es: " + dni);

        // Letra de ejemplar del DNI
        char ejemplar = 'A';
        System.out.println("La letra de ejemplar de mi DNI es: " + ejemplar);

        // Edad de mamá/papá/abuela/abuelo
        byte edadMama = 50;
        System.out.println("La edad de mi mamá es: " + edadMama);

        // Nombre y apellido de un prócer argentino
        String procer = "Manuel José Joaquín del Corazón de Jesús Belgrano";
        System.out.println("Un prócer argentino es: " + procer);

        // Número posible en un bingo
        int numeroBingo = 77;
        System.out.println("Número en un bingo: " + numeroBingo);

        // Precio de un celular
        double precioCelular = 379999.77;
        System.out.println("El precio de un celular es: $" + precioCelular);

        // Estatura en metros
        double estatura = 1.54;
        System.out.println("Mi estatura es: " + estatura + " metros");

        // Peso de una mascota en kilogramos
        double pesoMascota = 10.5;
        System.out.println("El peso de mi mascota es: " + pesoMascota + " kg");

        // Fecha de inicio y fin del 2do cuatrimestre
        String inicio2doCuatrimestre = "23/08/2025";
        String fin2doCuatrimestre = "21/11/2025";
        System.out.println("El 2do cuatrimestre inicia el: " + inicio2doCuatrimestre);
        System.out.println("El 2do cuatrimestre finaliza el: " + fin2doCuatrimestre);
    }

}
